-- Quien se apunta: su email, el perfil de su negocio (lo mismo que pregunta
-- el radar) y un token secreto para confirmar, cambiar el perfil o darse de
-- baja desde los enlaces de los correos. Nada más.
create table suscriptores (
	id uuid primary key,
	email varchar(254) not null unique,
	provincia varchar(6) not null,
	municipio varchar(80) not null,
	forma varchar(10) not null,
	empleados integer not null,
	antiguedad varchar(6) not null,
	sector varchar(1) not null,
	token varchar(64) not null unique,
	estado varchar(10) not null,
	-- Versión del aviso de privacidad que aceptó
	consentimiento varchar(20) not null,
	creado timestamp(6) with time zone not null,
	confirmado timestamp(6) with time zone,
	-- Último correo de alta enviado, para no repetirlo si se pulsa varias veces
	ultimo_alta timestamp(6) with time zone,
	ultimo_aviso timestamp(6) with time zone
);

-- Las convocatorias que ya se han repartido: una ayuda solo se avisa una vez
create table convocatorias_vistas (
	codigo varchar(20) primary key,
	vista timestamp(6) with time zone not null
);

-- Cada ayuda que encaja con alguien, hasta que sale en su correo
create table avisos (
	id bigint generated by default as identity primary key,
	suscriptor_id uuid not null references suscriptores (id) on delete cascade,
	codigo varchar(20) not null,
	estado varchar(6) not null,
	creado timestamp(6) with time zone not null,
	enviado timestamp(6) with time zone,
	unique (suscriptor_id, codigo)
);

create index avisos_pendientes on avisos (suscriptor_id) where enviado is null;
